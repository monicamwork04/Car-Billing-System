private void loadEmployees() {
    String sql = "SELECT emp_id, emp_name FROM tbl_emp";

    try (Connection con = JDBC.Con();
         PreparedStatement ps = con.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        jComboBox1.removeAllItems();

        while (rs.next()) {
            jComboBox1.addItem(rs.getString("emp_id"));
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error loading employees: " + e.getMessage());
    }
}

private void loadCustomers() {
    String sql = "SELECT cus_id, emp_id, cus_name, cus_phone FROM tbl_cus";

    try (Connection con = JDBC.Con();
         PreparedStatement ps = con.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        DefaultTableModel model = new DefaultTableModel(
            new String[]{"Customer ID", "Employee ID", "Customer Name", "Phone"}, 0
        );

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("cus_id"),
                rs.getString("emp_id"),
                rs.getString("cus_name"),
                rs.getString("cus_phone")
            });
        }

        jTable1.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error loading customers: " + e.getMessage());
    }
}

