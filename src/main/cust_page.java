    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        
    String cusId = jTextField1.getText().trim();

    if (cusId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter Customer ID");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this customer?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM tbl_cus WHERE cus_id = ?";

    try (Connection con = JDBC.Con();
         PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setString(1, cusId);

        int rows = ps.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(null, "Customer deleted successfully!");
            loadCustomers();
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "Customer ID not found!");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Delete failed: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton4ActionPerformed

