    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    Object selected = jComboBox1.getSelectedItem();

    if (selected == null) {
        JOptionPane.showMessageDialog(this, "Please select EMP ID");
        return;
    }

    String empId = selected.toString();
    String cusId = jTextField1.getText().trim();
    String cusName = jTextField2.getText().trim();
    String cusPhone = jTextField3.getText().trim();

    if (cusId.isEmpty() || cusName.isEmpty() || cusPhone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter all customer details");
        return;
    }

    String sql = "{call sp_cus_ins(?, ?, ?, ?, ?, ?)}";

    try (Connection con = JDBC.Con();
         java.sql.CallableStatement cs = con.prepareCall(sql)) {

        cs.setString(1, cusId);
        cs.setString(2, empId);
        cs.setString(3, cusName);
        cs.setString(4, cusPhone);
        cs.setString(5, new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss")
                .format(new java.util.Date()));

        cs.registerOutParameter(6, java.sql.Types.VARCHAR);

        cs.execute();

        String result = cs.getString(6);

        JOptionPane.showMessageDialog(this, result);

        if (result != null && result.contains("inserted")) {
            loadCustomers();
            clearForm();
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Add failed: " + e.getMessage());
    }



    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
      
    String cusId = jTextField1.getText().trim();
    String cusName = jTextField2.getText().trim();
    String cusPhone = jTextField3.getText().trim();

    Object selected = jComboBox1.getSelectedItem();

    if (selected == null || "--ID--".equals(selected.toString())) {
        JOptionPane.showMessageDialog(this, "Please select EMP ID");
        return;
    }

    String empId = selected.toString();

    if (cusId.isEmpty() || cusName.isEmpty() || cusPhone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter all customer details");
        return;
    }

    String sql = "UPDATE tbl_cus SET emp_id = ?, cus_name = ?, cus_phone = ? "
               + "WHERE cus_id = ?";

    try (Connection con = JDBC.Con();
         PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setString(1, empId);
        ps.setString(2, cusName);
        ps.setString(3, cusPhone);
        ps.setString(4, cusId);

        int rows = ps.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Customer updated successfully!");
            loadCustomers();
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "Customer ID not found!");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Edit failed: " + e.getMessage());
    }

    }//GEN-LAST:event_jButton2ActionPerformed

